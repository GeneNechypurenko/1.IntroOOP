using namespace std;

/*
==========================================================================================================================================
                                                         Конструктори і деструктор
==========================================================================================================================================

  1. Проблема неініціалізованих полів:
     Після створення об'єкта його поля містять «сміття», доки їх явно не заповнять. Метод init() або сеттери можна просто забути викликати.

  2. КОНСТРУКТОР — спеціальний метод, який викликається АВТОМАТИЧНО під час створення об'єкта і приводить його в коректний початковий стан.
     ПРАВИЛА ОБ'ЯВИ КОНСТРУКТОРУ:
     - ім'я збігається з ім'ям класу;
     - типу повернення НЕМАЄ (навіть void);
     - оголошується в public;
     - конструктори можуть бути 3-х видів:

  3. Види конструкторів:
     - За замовчуванням — без параметрів (або всі параметри мають значення за замовчуванням): Student s;
     - З параметрами: Student s("Олена", 20);
     - Перевантажені — кілька конструкторів з різними параметрами, тут компілятор обирає потрібний за переданими аргументами.

  4. Важливо
     - Немає ЖОДНОГО конструктора → компілятор створює порожній конструктор за замовчуванням (поля він не ініціалізує).
     - Написано БУДЬ-ЯКИЙ конструктор → конструктор за замовчуванням компілятор уже НЕ створює, і «Student s;» стає помилкою.

  5. Проблема витоку ресурсів: якщо поля класу використовують ресурси динамічної пам'яті, потрібно контролювати витоки пам'яті перед
    знищенням самого об'єкта. Для цього використовують деструктори.

  6. ДЕСТРУКТОР — спеціальний метод, який викликається АВТОМАТИЧНО під час знищення об'єкта і звільняє його ресурси.
     ПРАВИЛА ОБ'ЯВИ ДЕСТРУКТОРУ:
     - ім'я: ~ІмяКласу;
     - немає ні типу повернення, ні параметрів → деструктор лише ОДИН;
     - оголошується в public.

  7. ПРАВИЛО: Якщо конструктор виконав new → деструктор виконує delete / delete[].
*/

// Клас без конструктора — демонстрація проблеми
class Point
{
private:
    int x;
    int y;

public:
    void print()
    {
        cout << "(" << x << "; " << y << ")" << endl;
    }
};

class Student
{
private:
    char* name;   // ім'я тепер у динамічній пам'яті — рівно потрібного розміру
    int age;
    double averageGrade;

public:
    // Конструктор за замовчуванням
    Student()
    {
        name = nullptr;          // обов'язково до першого setName (там delete[])
        setName("Невідомий");
        age = 16;
        averageGrade = 0;
        cout << "  [+] Student(): " << name << endl;
    }

    // Конструктор з параметрами
    Student(const char* newName, int newAge)
    {
        name = nullptr;
        setName(newName);
        age = 16;               // спершу коректне значення,
        setAge(newAge);         // потім перевірка — у конструкторі можна викликати методи
        averageGrade = 0;
        cout << "  [+] Student(ім'я, вік): " << name << endl;
    }

    // Перевантажений конструктор
    Student(const char* newName, int newAge, double newGrade)
    {
        name = nullptr;
        setName(newName);
        age = 16;
        setAge(newAge);
        averageGrade = newGrade;
        cout << "  [+] Student(ім'я, вік, бал): " << name << endl;
    }

    // Деструктор: звільняє пам'ять, виділену під ім'я
    ~Student()
    {
        cout << "  [-] ~Student(): " << name << endl;
        delete[] name;
    }

    void setName(const char* newName)
    {
        delete[] name;                          // звільняємо старий рядок (delete[] nullptr — безпечно)
        int length = strlen(newName) + 1;    // +1 для '\0'
        name = new char[length];
        strcpy_s(name, length, newName);
    }

    bool setAge(int newAge)
    {
        if (newAge < 16 || newAge > 100)
        {
            return false;
        }
        age = newAge;
        return true;
    }

    void print()
    {
        cout << "  " << name << ", вік: " << age << ", середній бал: " << averageGrade << endl;
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // Без конструктора поля містять сміття (у режимі Debug — числа на кшталт -858993460)
    Point p;
    p.print();

    cout << "Початок main" << endl;
    Student a;                              // Student()

    {   // вкладений блок: об'єкти живуть лише до закривальної дужки
        cout << "Вхід у блок" << endl;
        Student b("Олена", 20);             // Student(const char*, int)
        Student c("Ігор", 500, 9.7);        // некоректний вік відхилено → 16
        c.setName("Ігор Коваленко");        // стара пам'ять звільнена в setName
        b.print();
        c.print();
        cout << "Вихід з блоку" << endl;
    }   // тут деструктори: спершу c, потім b

    a.print();
    cout << "Кінець main" << endl;
    return 0;
}   // тут деструктор a

/*
  ІНСАЙТИ / BEST PRACTICES

  1. Правило гарного стилю коду: Після конструктора об'єкт має бути ПОВНІСТЮ готовим до роботи: жодного неініціалізованого поля (сміття).

  2. ПАСТКА: Student s();  — це НЕ об'єкт, а оголошення ФУНКЦІЇ e, що повертає Student. Пишіть Student s; або Student s{};.
     Коли компілятор бачить рядок Student e();, він трактує його не як створення об'єкта, а як оголошення функції.

  3. В цьому прикладі є слабке місце - конструктори дублюють код (name = nullptr; setName...). Це дублювання приберається за допомогою принципа
     делегуванням конструкторів (пізніше в курсі).

  4. Деструктор не викликають ВРУЧНУ — це робить компілятор.

  5. УВАГА, класична ПАСТКА покажчик на покажчик: поки що НЕ копіюйте такі об'єкти Student d = a;
     Або передача Student у функцію за значенням.  Обидва об'єкти отримають ОДНУ адресу name, і деструктор двічі виконає delete[] для однієї
     пам'яті — програма впаде. Передавайте об'єкти за посиланням (Student&). Це слабке місце прибирається за допомогою — конструктору копіювання.

  6. Принцип «ресурс отримується в конструкторі, звільняється в деструкторі» називається RAII.
     На ньому побудовані стандартні класи С++ string, vector, розумні покажчики.

  ==========================================================================================================================================

  ПРАКТИКА
  1. Конструктори для класу Point.
     - Конструктор за замовчуванням Point() — встановлює x = 0, y = 0 і виводить повідомлення «Point()».
     - Конструктор Point(newX, newY) — встановлює координати через setX() і setY()
       (як Student(newName, newAge) викликає setAge) і виводить «Point(x, y)».
       Підказка: спершу присвойте полям 0, а потім викличте сеттери,
       щоб при некоректному значенні в полі не залишилося сміття.
     - У main: створіть Point a; і Point b(10, 20); виведіть обидві точки.
       Створіть Point c(150, 20); — переконайтеся, що x залишився 0.

  2. Клас IntArray (динамічний масив цілих чисел).
     - private-поля: int* data, int size.
     - Конструктор IntArray(newSize) — запам'ятовує розмір, виділяє пам'ять
       new int[size] і заповнює всі елементи нулями (циклом).
     - Деструктор ~IntArray() — звільняє пам'ять через delete[] data
       і виводить повідомлення «Масив знищено».
     - Модифікатор set(index, value) — записує value в елемент index,
       лише якщо index від 0 до size - 1; повертає true або false.
     - Інспектор get(index) — повертає елемент index; якщо індекс некоректний — повертає 0.
     - Метод print() — виводить усі елементи через пробіл.
     - У main: створіть IntArray arr(5); запишіть кілька значень, спробуйте
       set(10, 99) і виведіть повідомлення про помилку; виведіть масив.
       Створіть ще один IntArray усередині блоку { } і подивіться,
       коли з'явиться повідомлення деструктора.
*/
